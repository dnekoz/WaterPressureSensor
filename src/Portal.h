#pragma once

#include <Arduino.h>

// Запускает локальный HTTP-интерфейс, Wi-Fi STA и резервную точку доступа.
// Подключение к Wi-Fi не задерживает запуск измерений.
void portalBegin();

// Обслуживает фоновый веб-портал и следит за состоянием WiFi. Без delay().
void portalLoop();

bool portalWifiConnected();

// true ровно один раз после того, как настройки были сохранены с портала.
// Используется, чтобы переподключить MQTT с новыми параметрами.
bool portalConsumeSettingsChanged();

// Имя точки доступа, которую поднимает устройство в режиме настройки.
const char *portalApName();

// Пока поднята точка доступа с порталом, экран занят подсказкой (имя сети,
// пароль, адрес) — показания давления в этот момент никто не смотрит.
// true, если экран отрисован порталом и рабочий экран рисовать не нужно.
bool portalDrawIfActive();
