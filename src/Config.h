#pragma once

// Общие константы прошивки. Всё, что настраивается на портале, живёт в Settings.h;
// здесь только то, что меняется перепрошивкой.

#define FW_NAME "WaterPressureSensor"

// FW_VERSION приходит из build_flags (см. [common] в platformio.ini): её должны
// видеть и этот файл, и Logic.cpp, который Config.h не включает.
#ifndef FW_VERSION
#error "FW_VERSION не задана: соберите через PlatformIO, а не вручную"
#endif

// ---------------------------------------------------------------- дисплей ---

#define SCREEN_WIDTH   128
#define SCREEN_HEIGHT  64
#define SCREEN_ADDRESS 0x3C  // 0x3C у большинства модулей 128x64, реже 0x3D

// -1 = у модуля нет вывода RESET (обычный случай для I2C-плат SSD1306).
// В прежней версии тут стоял 0, то есть GPIO0 — boot/flash-пин D1 mini.
#define OLED_RESET -1

// --------------------------------------------------------------- измерение ---

#define SENSOR_PIN        A0
#define SENSOR_PERIOD_MS  20  // период выборки => окно ~0.64 с

// Пороги SENSOR_RAW_OVER и SENSOR_FAULT_MARGIN_V живут в Logic.h: они часть
// чистой логики пересчёта и покрыты тестами.

// ------------------------------------------------------------------ портал ---

// Резервная AP закрывается по таймауту только при сохранённой сети и без клиентов.
// Пароль генерируется отдельно для каждого устройства и хранится в Settings.
#define PORTAL_TIMEOUT_S 180

// -------------------------------------------------------------------- MQTT ---

// PubSubClient по умолчанию даёт 256 байт — в них не влезает discovery-payload
// Home Assistant, и publish() молча вернёт false.
#define MQTT_BUFFER_SIZE 1024

#define MQTT_RECONNECT_MIN_MS 5000UL
#define MQTT_RECONNECT_MAX_MS 30000UL

// Таймауты отдельных этапов. Общая длительность TLS может быть больше их суммы:
// BearSSL выполняет дополнительные операции и имеет собственные таймауты.

// Ожидание CONNACK. PubSubClient по умолчанию ждёт 15 с, и всё это время
// не обновляется экран и не отвечает веб-портал.
#define MQTT_SOCKET_TIMEOUT_S 4

// Установление TCP-соединения. WiFiClient по умолчанию даёт 5 с.
#define MQTT_TCP_TIMEOUT_MS 3000UL

// Разрешение имени брокера. Неотвечающий DNS блокирует отдельно от TCP.
#define MQTT_DNS_TIMEOUT_MS 3000UL

// --------------------------------------------------------------------- TLS ---

// Потолок размера загружаемого CA. Разумный сертификат — пара килобайт;
// ограничение защищает LittleFS от «выбрали не тот файл».
#define CA_MAX_SIZE 4096

// Сколько непрерывной памяти требовать перед рукопожатием. Проверяется именно
// максимальный свободный блок, а не сумма: приёмный буфер BearSSL должен быть
// непрерывным, и на фрагментированной куче рукопожатие падает при живых 30 КБ.
// Числа — приёмный буфер плюс контекст BearSSL с запасом.
#define TLS_MIN_BLOCK_MFLN  9000
#define TLS_MIN_BLOCK_FULL 23000

// Приёмный буфер TLS. Без MFLN запись TLS может быть до 16 КБ, и меньший буфер
// означает разрыв на середине рукопожатия.
#define TLS_RX_FULL 16384
#define TLS_RX_MFLN 1024
#define TLS_TX_SIZE 512

// Время до этой отметки считаем «часы не выставлены»: 2023-11-14. Проверять срок
// действия сертификата без часов бессмысленно, а BearSSL на это не укажет.
#define TLS_TIME_VALID_FROM 1700000000UL

// ------------------------------------------------------------- планировщик ---

#define DISPLAY_PERIOD_MS 250

// Пауза в loop(), после которой планировщик сдвигает точки отсчёта вместо того,
// чтобы навёрстывать пропущенные такты пачкой. Блокировать loop() надолго умеют
// попытка подключения к брокеру и рукопожатие TLS.
#define SCHEDULER_STALL_MS 500
