#pragma once

#include <Arduino.h>

#include "Sensor.h"

void mqttBegin();

// Обслуживает MQTT с паузами между повторами. Сама попытка connect() синхронна
// и может на несколько секунд задержать измерения и HTTP.
void mqttLoop();

// Публикует состояние на <base>/state. Вызывать раз в settings.mqttIntervalS.
void mqttPublishState(const Reading &r);

// Перечитывает настройки: рвёт текущее соединение и подключается заново.
void mqttApplySettings();

// false, если адрес брокера не задан — тогда MQTT просто выключен.
bool mqttEnabled();

bool mqttConnected();

// true ровно один раз после успешного подключения к брокеру. Нужен, чтобы
// опубликовать состояние сразу, а не ждать до конца текущего периода: при
// большом mqttIntervalS устройство иначе висело бы в Home Assistant без значения.
bool mqttConsumeJustConnected();

// Установлено ли сейчас соединение MQTT через TLS.
bool mqttTlsActive();

// Почему не удалось последнее рукопожатие. Пустая строка, если проблем нет.
// Показывается на портале: иначе «TLS не подключается» неотличимо от неверного
// пароля к брокеру.
const char *mqttTlsError();

// Причина последней неудачи подключения человеческим текстом — от неверного
// пароля до нехватки памяти под TLS. Пустая строка, если всё в порядке.
// Показывается на главной странице портала: без этого отказ выглядит как
// «MQTT просто не работает», без единой подсказки, что именно чинить.
const char *mqttLastError();
