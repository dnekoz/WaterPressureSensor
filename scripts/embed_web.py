"""Embed deterministic gzip web assets in firmware flash. No uploadfs step needed."""
from pathlib import Path
import gzip
import hashlib


def build_assets(root):
    root = Path(root)
    source = root / "web"
    output = root / ".pio" / "generated" / "WebAssets.h"
    files = [("INDEX", "index.html"), ("CSS", "app.css"), ("JS", "app.js")]
    version = hashlib.sha256(b"".join((source / name).read_bytes() for _, name in files)).hexdigest()[:12]
    lines = ["// Generated by scripts/embed_web.py; edit web/ instead.", "#pragma once", "#include <Arduino.h>"]
    sizes = []
    for symbol, filename in files:
        raw = (source / filename).read_bytes().replace(b"@ASSET_VERSION@", version.encode())
        compressed = gzip.compress(raw, compresslevel=9, mtime=0)
        tag = hashlib.sha256(raw).hexdigest()[:16]
        lines.append(f'static const char WEB_{symbol}_ETAG[] = "\\\"{tag}\\\"";')
        lines.append(f"static const uint8_t WEB_{symbol}[] PROGMEM = {{")
        for start in range(0, len(compressed), 20):
            lines.append(",".join(str(v) for v in compressed[start:start + 20]) + ",")
        lines.append("};")
        sizes.append(f"{filename}: {len(raw)} -> {len(compressed)} B")
    content = "\n".join(lines) + "\n"
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != content:
        output.write_text(content, encoding="utf-8")
    print("Web assets: " + "; ".join(sizes))
    return output.parent


try:
    Import("env")  # type: ignore[name-defined] # SCons
except NameError:
    if __name__ == "__main__":
        build_assets(Path(__file__).resolve().parents[1])
else:
    env.Append(CPPPATH=[str(build_assets(env["PROJECT_DIR"]))])  # type: ignore[name-defined]
